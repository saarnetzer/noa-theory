// Builds the installable, offline web app into dist/:
//   1. expo export -p web
//   2. dist/sw.js: a service worker that pre-caches every exported file (app code, questions,
//      all question images), so after the first visit the app runs fully offline
//   3. dist/404.html: copy of index.html so hosts without rewrites (GitHub Pages) serve app routes
// The site is served under app.json's experiments.baseUrl (e.g. /noa-theory on GitHub Pages).
// Usage: node scripts/build-web.mjs, then upload dist/ to any static HTTPS host.

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFile, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIST = join(ROOT, 'dist');
const SKIP = new Set(['sw.js', '404.html', '_redirects', 'metadata.json']);
const appConfig = JSON.parse(await readFile(join(ROOT, 'app.json'), 'utf8'));
const BASE = (appConfig.expo.experiments?.baseUrl ?? '').replace(/\/$/, '');

execFileSync('npx', ['expo', 'export', '--platform', 'web', '--clear'], { cwd: ROOT, stdio: 'inherit' });

async function files(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await files(full)));
    else out.push(full);
  }
  return out;
}

const all = (await files(DIST)).filter((f) => !SKIP.has(relative(DIST, f)));
const hash = createHash('sha256');
let bytes = 0;
const urls = [];
for (const file of all.sort()) {
  const data = await readFile(file);
  bytes += data.length;
  hash.update(relative(DIST, file)).update(data);
  urls.push(`${BASE}/` + relative(DIST, file).split(sep).map(encodeURIComponent).join('/'));
}
const version = hash.digest('hex').slice(0, 12);

const sw = `// Generated by scripts/build-web.mjs. Pre-caches the whole app for offline use.
const CACHE = 'noa-theory-${version}';
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    // Pages: try the network (picks up new versions), fall back to the cached app shell.
    event.respondWith(fetch(request).catch(() => caches.match('${BASE}/index.html')));
    return;
  }
  // Code, data and images are content-hashed or static: serve from cache first.
  event.respondWith(caches.match(request).then((hit) => hit || fetch(request)));
});
`;
await writeFile(join(DIST, 'sw.js'), sw);
await copyFile(join(DIST, 'index.html'), join(DIST, '404.html'));

console.log(`\nWeb app ready in dist/ for ${BASE || '/'}: ${urls.length} files pre-cached (${(bytes / 1e6).toFixed(1)} MB), version ${version}`);
